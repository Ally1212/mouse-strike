export function getFighterProfile(fighterId) {
  return FIGHTERS[fighterId] || FIGHTERS.f22;
}

export function getModuleChoices(fighterId) {
  return getFighterProfile(fighterId).modules;
}

export function getToolModes(fighterId) {
  return getFighterProfile(fighterId).toolModes;
}

export function getModuleById(fighterId, moduleId) {
  return getModuleChoices(fighterId).find((module) => module.id === moduleId) || null;
}
